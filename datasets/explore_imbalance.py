"""
Module 1 — Class imbalance analysis.
Reads HAM10000 metadata and ISIC 2019 ground truth CSV,
prints per-class image counts, and writes datasets/dataset_comparison.md.

Usage:
    python datasets/explore_imbalance.py
"""

import pathlib
import pandas as pd

DATA = pathlib.Path(__file__).parent.parent / "data"
OUT = pathlib.Path(__file__).parent / "dataset_comparison.md"

HAM_META = DATA / "ham10000" / "HAM10000_metadata.tab"
ISIC19_GT = DATA / "isic2019" / "ISIC_2019_Training_GroundTruth.csv"


def analyse_ham10000():
    df = pd.read_csv(HAM_META, sep="\t")
    counts = df["dx"].value_counts()
    total = len(df)
    print(f"\n=== HAM10000 ({total} images) ===")
    for cls, n in counts.items():
        print(f"  {cls:6s}  {n:5d}  ({n/total*100:.1f}%)")
    return total, counts


def analyse_isic2019():
    df = pd.read_csv(ISIC19_GT)
    # columns: image, MEL, NV, BCC, AK, BKL, DF, VASC, SCC, UNK
    class_cols = [c for c in df.columns if c != "image"]
    counts = df[class_cols].sum().astype(int).sort_values(ascending=False)
    total = len(df)
    print(f"\n=== ISIC 2019 ({total} images) ===")
    for cls, n in counts.items():
        print(f"  {cls:6s}  {n:5d}  ({n/total*100:.1f}%)")
    return total, counts


def count_images(folder: pathlib.Path, ext="*.jpg") -> int:
    if not folder.exists():
        return -1
    return len(list(folder.glob(ext))) + len(list(folder.glob(ext.upper())))


def write_comparison(ham_total, ham_counts, isic19_total, isic19_counts):
    isic18_imgs = count_images(DATA / "isic2018_seg" / "ISIC2018_Task1-2_Training_Input")
    isic18_masks = count_images(DATA / "isic2018_seg" / "ISIC2018_Task1_Training_GroundTruth", "*.png")
    isic19_imgs = count_images(DATA / "isic2019" / "ISIC_2019_Training_Input")

    def fmt(n):
        return str(n) if n >= 0 else "not extracted yet"

    lines = [
        "# Module 1 — Dataset Comparison\n",
        f"_Generated by `datasets/explore_imbalance.py`_\n",
        "",
        "## Summary table\n",
        "| Dataset | Images (verified) | Classes | Annotation | License | Source |",
        "|---|---|---|---|---|---|",
        f"| HAM10000 | {ham_total} | 7 (NV, MEL, BCC, AKIEC, BKL, DF, VASC) | Diagnosis label + patient metadata | CC BY-NC 4.0 | ISIC Archive / Harvard Dataverse / Kaggle |",
        f"| ISIC 2018 Task 1 (Segmentation) | {fmt(isic18_imgs)} images / {fmt(isic18_masks)} masks | Binary lesion mask | Pixel-level segmentation | CC BY-NC 4.0 | isic-challenge-data.s3.amazonaws.com |",
        f"| ISIC 2019 | {fmt(isic19_imgs)} images ({isic19_total} labelled) | 8 (HAM7 + SCC) | Diagnosis label + metadata | CC BY-NC 4.0 | isic-challenge-data.s3.amazonaws.com |",
        "| BCN20000 | 18,946 (not downloaded) | 8 | Diagnosis label | CC BY-NC 4.0 | ISIC Archive |",
        "| PH2 | 200 (not downloaded) | 3 (melanoma, atypical, benign) | Diagnosis + pixel mask | Research only | dermdermoscopy.org |",
        "| ISIC 2024 SLICE-3D | 401,059 (not downloaded) | Malignant / benign | Diagnosis + rich CSV metadata | CC BY-NC 4.0 | Kaggle competition (requires rule acceptance) |",
        "",
        "## HAM10000 class imbalance\n",
        "| Class | Count | % |",
        "|---|---|---|",
    ]
    for cls, n in ham_counts.items():
        lines.append(f"| {cls} | {n} | {n/ham_total*100:.1f}% |")

    lines += [
        "",
        "## ISIC 2019 class distribution\n",
        "| Class | Count | % |",
        "|---|---|---|",
    ]
    for cls, n in isic19_counts.items():
        lines.append(f"| {cls} | {n} | {n/isic19_total*100:.1f}% |")

    lines += [
        "",
        "## Notes for Module 4\n",
        "- HAM10000 NV:DF ratio is ~50:1 — use class-weighted cross-entropy or focal loss.",
        "- ISIC 2019 is better balanced but still MEL/NV heavy.",
        "- ISIC 2018 Task 1 segmentation masks are the ground truth for the segmentation stage.",
        "- ISIC 2024 SLICE-3D is the generalization test set (phone-camera-like images) — do NOT train on it.",
    ]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {OUT}")


def main():
    ham_total, ham_counts = analyse_ham10000()
    isic19_total, isic19_counts = analyse_isic2019()
    write_comparison(ham_total, ham_counts, isic19_total, isic19_counts)


if __name__ == "__main__":
    main()
